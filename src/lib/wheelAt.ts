/** 휠 이벤트가 **커서 아래 요소의 것인가** — 브라우저의 「휠 래칭」을 걷어내는 판정.
 *
 *  ★★**Chromium 은 휠 제스처를 처음 잡은 요소에 매어 둔다**(wheel latching). 한 번 시작된
 *    제스처는 **커서를 다른 데로 옮겨도 그 요소로 계속 배달된다** — 제스처가 끝났다고 볼
 *    만큼 쉬거나, 클릭 같은 다른 입력이 들어와야 풀린다. 스크롤이 실제로 일어나지 않는
 *    자리(`preventDefault` 로 막는 우리 칩 같은 곳)에서는 특히 오래 매여 있다.
 *
 *  ★실제로 밟은 자국 (사용자 지적 2026-08-24): *"알트 휠로 가중치 조절한 후에 그 상태로
 *    이미지 프리뷰 위에 커서를 옮겨서 휠을 하면 이미지 휠이 작동 안 함. 한번 클릭해서
 *    포커스를 풀어야만 휠이 됨."* 칩에 매여 있으니 프리뷰는 이벤트를 아예 못 받고,
 *    반대로 **칩은 커서가 떠났는데도 가중치를 계속 바꾸고 있었다.**
 *
 *  ★고치는 자리는 **양쪽 다**여야 한다: 받는 쪽이 「내 위인가」를 묻고, 뺏기는 쪽은
 *    「내 위가 아니면 손대지 않는다」를 지킨다. 한쪽만 고치면 이벤트가 허공에 뜬다.
 *  ★래칭 자체는 못 끈다 (브라우저 내부 상태다). 그래서 **좌표로 판정**한다 — 이벤트가
 *    누구에게 배달되든 커서가 있는 곳은 하나뿐이다.
 */
export function wheelIsOver(el: Element | null | undefined, e: WheelEvent): boolean {
  if (!el) return false;
  const r = el.getBoundingClientRect();
  const inBox =
    e.clientX >= r.left && e.clientX <= r.right && e.clientY >= r.top && e.clientY <= r.bottom;
  if (!inBox) return false;
  /* ★★**위에 덮인 것이 있으면 내 것이 아니다** (사용자 지적 2026-08-25: *"생성된 이미지의
       「프롬프트 보기」로 모달을 열고 스크롤하면 뒤의 이미지가 전환됨"*).
     네모 안인지만 보면, **모달이 그 위를 덮고 있어도** 좌표는 여전히 프리뷰 안이다.
     그래서 모달을 굴리는 휠이 뒤의 그림을 넘겼다.
     ★커서 아래의 **맨 위 요소**를 물어 그것이 내 안의 것인지 본다 — 창이든 말풍선이든
       무엇이 덮여도 같은 규칙으로 걸러진다 (모달마다 예외를 적지 않는다).
     ★`pointer-events: none` 인 껍데기는 애초에 안 잡히므로 그런 덮개는 방해하지 않는다. */
  const hit = el.ownerDocument.elementFromPoint(e.clientX, e.clientY);
  return !!hit && (el === hit || el.contains(hit));
}
